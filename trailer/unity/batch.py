"""Record trailer takes in BATCHMODE Unity, in a game worktree, without the editor.

    python trailer/unity/batch.py <game-worktree> <take> [<take> ...]

The same takes (takes.py) and the same driver (driver.cs.tmpl) as record.py, but
generated into a PlayMode test, Assets/Tests/PlayMode/QaTrailerTakes.cs in the
worktree (never commit it), and run by `Unity -batchmode -runTests`. Use it when
the open editor is busy (balance sims), or for a hands-off re-record.

What differs from the editor path (record.py), and why:
- No Game view: the world camera renders into a portrait 1080x1920 RT, which also
  gives CameraFit a portrait aspect. The overlay canvases are moved onto the WORLD
  camera (ScreenSpaceCamera, in front of the sprites, sorted above them) every
  frame, since scene reloads and modals bring new ones. A second camera for the UI
  does not work: in URP it is a base camera and clears the field away (#314D79).
- Batchmode never fires WaitForEndOfFrame: each driver step runs once a frame on a
  plain yield, and copies the RT the world camera finished last frame.
- Tap rings: buttons resolve through their canvas camera (now the world camera), so
  the logged positions are in the same 1080x1920 frame as the pictures.
- The worktree needs its own productName (a separate save); the take writes one
  veteran save there, as the editor path does. Delete it afterwards.
Frames, taps.txt, events.txt and meta.txt land in trailer/build/takes/<take>/,
exactly where make_trailer.py reads them.
"""
import os
import re
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import takes as T  # noqa: E402

OUT = os.path.abspath(os.path.join(HERE, "..", "build", "takes")).replace("\\", "/")
UNITY = r"C:\Program Files\Unity\Hub\Editor\6000.4.2f1\Editor\Unity.exe"
FLIP = False  # unlike ScreenCapture, a camera RT reads back top-down already (checked 2026-11-20)


def driver_body(spec):
    """driver.cs.tmpl, filled for one take and adapted to run inside an iterator."""
    src = open(os.path.join(HERE, "driver.cs.tmpl"), encoding="utf-8").read()
    for k, v in {"TAKE": spec["name"], "SETTLE": str(spec.get("settle", 30)), "LENGTH": str(spec["length"]),
                 "OUTDIR": OUT, "KEEP": spec.get("keep", ""), "READY": spec.get("ready", "return gm != null && gm.Playing;"),
                 "CUES": spec.get("cues", ""), "FLIP": "true" if FLIP else "false"}.items():
        src = src.replace("@@" + k + "@@", v)
    swaps = [
        ("int W = Screen.width, H = Screen.height;", "int W = QaTrailerTakes.W, H = QaTrailerTakes.H;"),
        ("var eof = new WaitForEndOfFrame();", "object eof = new object();   // batchmode: one step a frame"),
        ("ScreenCapture.CaptureScreenshotIntoRenderTexture(rt);", "QaTrailerTakes.OntoWorld(); Graphics.Blit(QaTrailerTakes.WorldRt, rt);"),
    ]
    for a, b in swaps:
        assert src.count(a) == 1, a
        src = src.replace(a, b)
    # the host GameObject and its coroutine: the test iterates the steps itself
    i = src.index("var hostGo = GameObject.Find(\"TrailerHost\");")
    j = src.index("host.StopAllCoroutines();") + len("host.StopAllCoroutines();")
    src = src[:i] + src[j:]
    i = src.index("host.StartCoroutine(steps.GetEnumerator());")
    src = src[:i] + "foreach (var _step in steps) { QaTrailerTakes.OntoWorld(); yield return null; }\n"
    # the driver keeps per-frame canvases on the world camera before each step too
    src = src.replace("System.Action keep = () =>\n{", "System.Action keep = () =>\n{\n    QaTrailerTakes.OntoWorld();", 1)
    return src


def generate(names):
    parts = ["""// GENERATED by heroarcher-site/trailer/unity/batch.py: QA ONLY, never commit.
using System;
using System.Collections;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.SceneManagement;
using UnityEngine.TestTools;

public class QaTrailerTakes
{
    public const int W = 1080, H = 1920;
    public static RenderTexture WorldRt;

    [TearDown]
    public void Wipe()
    {
        SceneManager.sceneLoaded -= Portrait;
        Time.captureDeltaTime = 0f;
        typeof(ScenarioRunner).GetProperty("Current").SetValue(null, null, null);
        DevFlags.Reset(); Unlocks.DevAll = false; Time.timeScale = 1f;
    }

    static void Portrait(Scene s, LoadSceneMode m) => OntoWorld(true);
    static int lastScan = -100;

    // the world camera draws into the portrait RT; overlay canvases ride on it. The
    // canvas scan is the expensive part: on a scene load, a new camera, or every 15
    // frames (a frame's budget matters: unscaled-time effects follow the wall clock)
    public static void OntoWorld(bool force = false)
    {
        if (WorldRt == null) { WorldRt = new RenderTexture(W, H, 24); WorldRt.Create(); }
        var cam = Camera.main;
        if (cam == null) return;
        if (cam.targetTexture != WorldRt) { cam.targetTexture = WorldRt; force = true; }
        if (!force && Time.frameCount - lastScan < 15) return;
        lastScan = Time.frameCount;
        foreach (var c in UnityEngine.Object.FindObjectsByType<Canvas>(FindObjectsSortMode.None))
            if (c.isRootCanvas && c.renderMode == RenderMode.ScreenSpaceOverlay)
            {
                c.renderMode = RenderMode.ScreenSpaceCamera; c.worldCamera = cam; c.planeDistance = 1f;
                c.sortingOrder = 1000 + c.sortingOrder;
            }
    }

    static IEnumerator Boot()
    {
        // a fresh scene per take; the take's PRELUDE writes its own veteran save
        SceneManager.sceneLoaded -= Portrait; SceneManager.sceneLoaded += Portrait;
        typeof(ScenarioRunner).GetProperty("Current").SetValue(null, null, null);
        MetaState.ResetForTests();
        SceneManager.LoadScene("SampleScene");
        yield return null; yield return null;
        yield return MenuReady();
    }

    static IEnumerator MenuReady()
    {
        float t0 = Time.realtimeSinceStartup;
        while (Time.realtimeSinceStartup - t0 < 60f)
        {
            if (GameManager.I != null && GameManager.I.State == GameState.Menu && Time.timeSinceLevelLoad > 1.5f) break;
            yield return null;
        }
        yield return null;
    }
"""]
    for name in names:
        spec = dict(T.TAKES[name]); spec["name"] = name
        cs = re.sub(r"\W", "_", name)
        pre = spec.get("pre", "")
        setup = spec.get("setup", "return \"no setup\";")
        parts.append("""
    static string Pre_%(cs)s()
    {
%(prelude)s
%(pre)s
    }
    static string Setup_%(cs)s()
    {
%(prelude)s
%(setup)s
    }
    [UnityTest, Timeout(1800000)]
    public IEnumerator Take_%(cs)s()
    {
        yield return Boot();
        %(runpre)s
        Debug.Log("[Trailer] %(name)s setup: " + Setup_%(cs)s());
        yield return null;
%(body)s
        Debug.Log("[Trailer] %(name)s: " + System.IO.File.ReadAllText(outDir + "/meta.txt").Replace("\\n", " | "));
    }
""" % dict(cs=cs, name=name, prelude=T.PRELUDE, pre=pre if pre else 'return "no pre";', setup=setup,
           runpre=('Debug.Log("[Trailer] %s pre: " + Pre_%s()); yield return null; yield return MenuReady();' % (name, cs)) if pre else "",
           body=driver_body(spec)))
    parts.append("}\n")
    return "".join(parts)


def main():
    wt, names = sys.argv[1], sys.argv[2:]
    for n in names:
        assert n in T.TAKES, "no take " + n
    path = os.path.join(wt, "Assets", "Tests", "PlayMode", "QaTrailerTakes.cs")
    open(path, "w", encoding="utf-8").write(generate(names))
    print("generated", path)
    if "--no-run" in os.environ.get("BATCH_FLAGS", ""):
        return
    log = os.path.join(HERE, "..", "build", "batch_log.txt")
    res = os.path.join(HERE, "..", "build", "batch_results.xml")
    filt = ";".join("QaTrailerTakes.Take_" + re.sub(r"\W", "_", n) for n in names)
    t0 = time.time()
    subprocess.run([UNITY, "-batchmode", "-projectPath", wt, "-runTests", "-testPlatform", "PlayMode",
                    "-testFilter", filt, "-testResults", os.path.abspath(res), "-logFile", os.path.abspath(log)])
    print("unity done in %.0fs" % (time.time() - t0))
    for n in names:
        meta = os.path.join(OUT, n, "meta.txt")
        print(" ", n, open(meta).read().replace("\n", " | ") if os.path.exists(meta) else "NO META (see build/batch_log.txt)")


if __name__ == "__main__":
    main()
